"""Small product-facing execution and independently checked completion records."""

from __future__ import annotations

from collections.abc import Awaitable, Callable
from enum import StrEnum

from pydantic import BaseModel, ConfigDict, Field


class EngineStatus(StrEnum):
    COMPLETED = "completed"
    PARTIALLY_COMPLETED = "partially_completed"
    BLOCKED = "blocked"
    FAILED = "failed"
    CANCELLED = "cancelled"


class PageEvidence(BaseModel):
    model_config = ConfigDict(frozen=True, extra="forbid")
    url: str
    title: str
    headings: list[str]


class CompletionCriteria(BaseModel):
    """Caller-owned checks for navigation; never generated by the decision model."""

    model_config = ConfigDict(frozen=True, extra="forbid")
    url: str = Field(min_length=1)
    heading: str = Field(min_length=1)

    def verify(self, evidence: PageEvidence | None) -> bool:
        if evidence is None:
            return False
        # Preserve query/fragment values exactly. Stripping the whole URL can
        # turn a different receipt value such as city=Pune/ into city=Pune.
        plain_paths = all("?" not in url and "#" not in url for url in (evidence.url, self.url))
        same_url = evidence.url == self.url or (
            plain_paths and evidence.url.rstrip("/") == self.url.rstrip("/")
        )
        return same_url and self.heading in evidence.headings


class EngineEvent(BaseModel):
    model_config = ConfigDict(frozen=True, extra="forbid")
    kind: str
    engine: str = "fast"
    provider: str
    model: str | None = None
    step: int = 0
    operation: str | None = None
    candidate_id: str | None = None
    verified: bool | None = None
    latency_ms: float | None = None
    error: str | None = None

    async def publish(self, sink: EventSink | None) -> None:
        from browser_agent.telemetry.debug_log import record_debug

        record_debug("engine.event", self.model_dump(mode="json"), step=self.step)
        if sink is not None:
            await sink(self)


EventSink = Callable[[EngineEvent], Awaitable[None]]


class EngineResult(BaseModel):
    model_config = ConfigDict(frozen=True, extra="forbid")
    status: EngineStatus
    engine: str = "fast"
    provider: str
    model: str
    answer: str | None = None
    evidence: PageEvidence | None = None
    verified: bool = False
    steps: int = 0
    action_count: int = 0
    generative_calls: int = 0
    provider_errors: int = 0
    recovery_count: int = 0
    decision_latencies_ms: list[float] = Field(default_factory=list[float])
    duration_ms: float = 0
    failure_phase: str | None = None
    run_id: str | None = None
    error: str | None = None
